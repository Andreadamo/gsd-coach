// ID deterministici in formato UUID (compatibili con Supabase)
export const seedId = (n: number) => `5eed0000-0000-4000-8000-${n.toString(16).padStart(12, '0')}`

type XY = [number, number]
type I = [ItemType, string | undefined, number, number, Record<number, XY>?, number?]
type A = [ArrowKind, number, number, number, number, number, number?]

let ctr = 0
function dg(preset: FieldPreset, w: number, h: number, steps: (string | [string, string])[], items: I[], arrows: A[]): Diagram {
  return {
    field: { preset, w, h },
    steps: steps.map((s) => (typeof s === 'string' ? { title: s } : { title: s[0], note: s[1] })),
    items: items.map(([type, label, x, y, kf, rot]) => {
      const pos: Record<number, { x: number; y: number }> = { 0: { x, y } }
      if (kf) for (const [k, [px, py]] of Object.entries(kf)) pos[Number(k)] = { x: px, y: py }
      return { id: `it${++ctr}`, type, label, pos, rot }
    }),
    arrows: arrows.map(([kind, step, x1, y1, x2, y2, curve]) => ({ id: `ar${++ctr}`, kind, step, from: { x: x1, y: y1 }, to: { x: x2, y: y2 }, curve })),
  }
}

